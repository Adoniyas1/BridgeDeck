/** A lab notebook entry: a note laid out like a lab report, with a calculator block for theory and
 *  measurements (units, and % error worked out), a circuit block to check the setup, and sections
 *  to fill in. Exported as a typeset PDF from the note (its PDF button). */
export function labNotebookMarkdown(course: string, title: string, date = new Date()) {
  return [
    `# ${title}`,
    '',
    `*${course} · ${date.toLocaleDateString([], { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' })} · partners: *`,
    '',
    '## Objective',
    '',
    'What this lab shows or measures.',
    '',
    '## Equipment',
    '',
    '- ',
    '',
    '## Circuit',
    '',
    '```spice',
    'V1 in 0 12V',
    'R1 in out 4.7k',
    'R2 out 0 10k',
    '? V(out)',
    '```',
    '',
    '## Theory and data',
    '',
    '```calc',
    '# Expected (units work: 4.7k ohm, 10uF, 2.2mA)',
    'R1 = 4.7k ohm',
    'R2 = 10k ohm',
    'Vin = 12V',
    'Vth = Vin * R2 / (R1 + R2)',
    '# Measured, and % error against theory',
    'Vm = 8.05V',
    'err = abs(Vm - Vth) / Vth * 100',
    '```',
    '',
    '## Results and discussion',
    '',
    'What the numbers show, and why measured and expected differ.',
    '',
    '## Conclusion',
    '',
  ].join('\n')
}
